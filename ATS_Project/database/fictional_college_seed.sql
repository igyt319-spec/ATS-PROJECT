SELECT s.register_number, CONCAT(s.first_name,' ',s.last_name) AS student_name, d.department_code,
       ROUND(AVG(m.total_marks),2) AS average_marks, ROUND(AVG(a.attendance_percentage),2) AS average_attendance
FROM students s
JOIN departments d ON d.department_id = s.department_id
LEFT JOIN marks m ON m.student_id = s.student_id
LEFT JOIN attendance a ON a.student_id = s.student_id AND a.subject_id = m.subject_id
GROUP BY s.student_id, s.register_number, s.first_name, s.last_name, d.department_code
ORDER BY s.student_id LIMIT 10;

